const input = process.argv[2] || 'DESIGN.md';
const output = process.argv[3] || `App/themes/${path.basename(input, path.extname(input)).toLowerCase()}.ts`;
const parsed = parseYaml(fs.readFileSync(input, 'utf8'));
const theme = camelizeKeys(resolveRefs(parsed, parsed));
const name = String(theme.name || path.basename(input, path.extname(input))).replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase());
const id = path.basename(output, path.extname(output)).toLowerCase();
const content = `// Generated by scripts/extract-theme.mjs from ${input}.\nexport const theme = ${JSON.stringify({ ...theme, id }, null, 2)} as const;\nexport default theme;\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, content);
console.log(`Extracted ${theme.name || name} -> ${output}`);
